#!/usr/bin/env python3
"""Check 'From the market' is exempt from the claims gate only where the catalog generated it."""

import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from hass import claims  # noqa: E402


NAME = "npp_market_brand_default"
MISSING = "Producer not identified"
MARKET = "From the market"


def _product(key, name, brand, display, before=None, collection="products"):
    return {"collection": collection, "key": key, "before": before,
            "after": {"id": key, "name": name, "brand": brand, "displayBrand": display}}


def _add(name, brand, **extra):
    return {"op": "product.add", "args": {"name": name, "brand": brand, **extra}}


CASES = [
    # 0: generated by the catalog for an unidentified producer: exempt
    {"ops": [_add("Plum Jam", MISSING)],
     "records": [_product("photo-product-012", "Plum Jam", MISSING, MARKET)]},
    # 1: the op supplied the same label itself: not exempt
    {"ops": [_add("Plum Jam", MISSING, displayBrand=MARKET)],
     "records": [_product("photo-product-012", "Plum Jam", MISSING, MARKET)]},
    # 2: the producer is named: not exempt
    {"ops": [_add("Plum Jam", "Cedar Row Apiary")],
     "records": [_product("photo-product-012", "Plum Jam", "Cedar Row Apiary", MARKET)]},
    # 3: the record name differs from the op: not exempt
    {"ops": [_add("Plum Jam", MISSING)],
     "records": [_product("photo-product-012", "Organic Plum Jam", MISSING, MARKET)]},
    # 4: an existing record (before is not None): not exempt
    {"ops": [_add("Plum Jam", MISSING)],
     "records": [_product("photo-product-012", "Plum Jam", MISSING, MARKET,
                          before={"id": "photo-product-012"})]},
    # 5: a different label: not exempt
    {"ops": [_add("Plum Jam", MISSING)],
     "records": [_product("photo-product-012", "Plum Jam", MISSING, "Best in Town")]},
    # 6: any op other than product.add: not exempt
    {"ops": [{"op": "product.edit", "args": {"name": "Plum Jam", "brand": MISSING}}],
     "records": [_product("photo-product-012", "Plum Jam", MISSING, MARKET)]},
    # 7: two adds paired one to one; only the second is generated
    {"ops": [_add("Fig Jam", "Harbor Lane Farm"), _add("Plum Jam", MISSING)],
     "records": [_product("photo-product-013", "Fig Jam", "Harbor Lane Farm", "Harbor Lane Farm"),
                 _product("photo-product-012", "Plum Jam", MISSING, MARKET)]},
    # 8: nothing at all
    {"ops": [], "records": []},
    # 9: not a product record: not exempt
    {"ops": [_add("Plum Jam", MISSING)],
     "records": [_product("photo-product-012", "Plum Jam", MISSING, MARKET, collection="makers")]},
]

MUST_EMPTY = (1, 2, 3, 4, 5, 6, 8, 9)

EXPECTED = [
    "case 0 defaulted=[0]",
    "case 1 defaulted=[]",
    "case 2 defaulted=[]",
    "case 3 defaulted=[]",
    "case 4 defaulted=[]",
    "case 5 defaulted=[]",
    "case 6 defaulted=[]",
    "case 7 defaulted=[1]",
    "case 8 defaulted=[]",
    "case 9 defaulted=[]",
]


def run():
    """Return the output lines and whether every check passed."""
    lines, failed = [], False
    for i, draft in enumerate(CASES):
        try:
            got = claims._defaulted(draft)
            line = f"case {i} defaulted={sorted(got)!r}"
        except Exception:
            lines.append("FAIL check-error")
            return lines, True
        lines.append(line)
        if i in MUST_EMPTY and got:
            lines.append(f"FAIL supplied-brand-exempted {i}")
            failed = True
        if line != EXPECTED[i]:
            lines.append(f"FAIL defaulted-changed {i}")
            failed = True
    return lines, failed


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args(argv)
    lines, failed = run()
    for line in lines:
        print(line)
    print(f"FAIL {NAME}" if failed else f"PASS {NAME}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
